import { chromium } from "playwright-core";
const b = await chromium.launch({ channel: "chrome", headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
await p.goto("http://127.0.0.1:8765/?lang=en", { waitUntil: "networkidle" });
const box = await p.locator("#wheel > svg.wsvg").boundingBox();
const k = box.width / 480;
const at = (lx, ly) => [box.x + lx * k, box.y + ly * k];
const pol = (r, d) => at(240 + Math.cos((d * Math.PI) / 180) * r, 240 + Math.sin((d * Math.PI) / 180) * r);
const hub = async () => (await p.locator(".whub").innerText()).replace(/\n/g, " | ");
const out = {};
await p.mouse.click(...at(240, 240 + 158 + 12 + 17));
out.mode = await p.locator(".wtab.on").innerText();
await p.mouse.move(...pol(106, 150), { steps: 4 });
out.rotate = await hub();
out.subOpen = await p.locator(".w-sub.open").count();
await p.mouse.move(...pol(191, 150), { steps: 4 });
await p.mouse.move(...pol(191, 128), { steps: 4 });
out.option = await hub();
await p.screenshot({ path: "/tmp/site-wheel-hover.png", clip: { x: box.x - 40, y: box.y - 40, width: box.width + 80, height: box.height + 80 } });
await p.mouse.click(...pol(191, 128));
await p.waitForTimeout(400);
out.card = (await p.locator(".wcard").innerText()).replace(/\n/g, " | ");
out.cardShown = await p.locator(".wcard.show").count();
await p.screenshot({ path: "/tmp/site-wheel-run.png", clip: { x: box.x - 40, y: box.y - 40, width: box.width + 80, height: box.height + 80 } });
// keyboard: focus wheel, Shift tap → convert, arrows
await p.mouse.move(10, 10);
await p.locator("#wheel").focus();
await p.keyboard.press("Shift");
out.afterShift = await p.locator(".wtab.on").innerText();
await p.keyboard.press("ArrowRight"); await p.keyboard.press("ArrowRight");
out.keyHub = await hub();
await p.keyboard.press("Enter");
await p.waitForTimeout(300);
out.keyCard = (await p.locator(".wcard").innerText()).replace(/\n/g, " | ");
// ring tabs + slider + dest
await p.locator("#tab-actions").click();
out.actionsVisible = await p.locator("#panel-actions").isVisible();
await p.locator("#ba-range").fill("20");
out.baX = await p.locator("#ba").evaluate((e) => e.style.getPropertyValue("--x"));
await p.locator('.dest[data-dest="clipboard"]').click();
out.dest = await p.locator("#dest-sub-out").innerText();
await p.locator('#langs button[data-l="ja"]').click();
out.ja = await p.locator("#lang-show").innerText();
await p.locator("#lang-select").selectOption("ko");
out.koTitle = await p.title();
out.koH1 = await p.locator("h1").innerText();
out.koWheelTab = await p.locator(".wtab.on").innerText();
out.dmg = await p.locator(".dl-link").first().getAttribute("href");
out.errs = errs;
console.log(JSON.stringify(out, null, 1));
await b.close();

