#!/usr/bin/env node
// Builds the icon font subset and windows/src/Pickverter/UI/Glyphs.g.cs from scripts/icons.json, which maps the
// SF Symbol names used by the shared core ("photo", "rotate.right"…) to Fluent UI System Icons (MIT).
//
//   FLUENT_DIR=/path/to/fonts node scripts/make-glyphs.mjs
//
// FLUENT_DIR holds FluentSystemIcons-Regular/Filled .ttf and .json from
// https://github.com/microsoft/fluentui-system-icons/tree/main/fonts. pyftsubset (fontTools) must be on PATH
// or given as PYFTSUBSET.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fluent = process.env.FLUENT_DIR ?? "/tmp/fluent";
const subset = process.env.PYFTSUBSET ?? "pyftsubset";
const sizes = [20, 24, 16, 28, 32, 48, 12];
const icons = JSON.parse(readFileSync(join(root, "scripts/icons.json"), "utf8"));
const tables = {
  regular: JSON.parse(readFileSync(join(fluent, "FluentSystemIcons-Regular.json"), "utf8")),
  filled: JSON.parse(readFileSync(join(fluent, "FluentSystemIcons-Filled.json"), "utf8")),
};

function resolve(candidate) {
  const filled = candidate.startsWith("fill:");
  const name = filled ? candidate.slice(5) : candidate;
  const style = filled ? "filled" : "regular";
  for (const size of sizes) {
    const code = tables[style][`ic_fluent_${name}_${size}_${style}`];
    if (code !== undefined) return { style, code };
  }
  return null;
}

const used = { regular: new Set(), filled: new Set() };
const lines = [];
const missing = [];
for (const [symbol, candidates] of Object.entries(icons)) {
  const hit = candidates.map(resolve).find(Boolean);
  if (!hit) {
    missing.push(symbol);
    continue;
  }
  used[hit.style].add(hit.code);
  lines.push(`        ["${symbol}"] = (${hit.style === "filled" ? "true" : "false"}, 0x${hit.code.toString(16).toUpperCase()}),`);
}
if (missing.length) {
  console.error("no Fluent glyph for: " + missing.join(", "));
  process.exit(1);
}

const out = join(root, "src/Pickverter/Resources/Fonts");
mkdirSync(out, { recursive: true });
for (const style of ["regular", "filled"]) {
  const font = join(fluent, `FluentSystemIcons-${style === "filled" ? "Filled" : "Regular"}.ttf`);
  const unicodes = [...used[style]].map((code) => "U+" + code.toString(16).toUpperCase()).join(",");
  execFileSync(subset, [font, "--unicodes=" + unicodes, "--layout-features=", "--no-hinting", "--desubroutinize",
    "--output-file=" + join(out, `PickverterIcons-${style === "filled" ? "Filled" : "Regular"}.ttf`)], { stdio: "inherit" });
}

const source = `// Generated by scripts/make-glyphs.mjs from scripts/icons.json. Do not edit.
namespace Pickverter.UI;

internal static partial class Glyphs
{
    private static readonly Dictionary<string, (bool Filled, int Code)> Table = new(StringComparer.Ordinal)
    {
${lines.join("\n")}
    };
}
`;
mkdirSync(join(root, "src/Pickverter/UI"), { recursive: true });
writeFileSync(join(root, "src/Pickverter/UI/Glyphs.g.cs"), source);
console.log(`${lines.length} glyphs · regular ${used.regular.size} · filled ${used.filled.size}`);

